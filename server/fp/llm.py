DEFAULT_ANGLE = "demo"

#: С какого бюджета отклик сам предлагает цену ниже (с 08.11.2026, по просьбе
#: владельца): на заказ «под 200 000» он отвечает «около 100 000». Ниже
#: планки цена не называется вовсе. Сумму считает парсер, а не модель: так
#: она одинакова в GRAVITAS и в облачном пути, и модель не сочиняет свою.
DISCOUNT_FROM = 150_000
DISCOUNT_SHARE = 0.5


def discount_price(price: str):
    """Сколько назвать в отклике, если бюджет большой. Иначе None."""
    top = top_budget(price)
    if top is None or top < DISCOUNT_FROM:
        return None
    return int(round(top * DISCOUNT_SHARE, -4))


def draft_hint(angle: str, price: str) -> str:
    """Инструкция под конкретный заказ: заход и что делать с ценой."""
    parts = [ANGLES.get(angle) or ANGLES[DEFAULT_ANGLE]]
    offer = discount_price(price)
    if offer:
        amount = f"{offer:,}".replace(",", " ")
        parts.append(
            "ЦЕНА ДЛЯ ЭТОГО ЗАКАЗА. Бюджет большой, назови цену ниже его: "
            f"«стоить будет дешевле чем предлагаете, в среднем по рынку около "
            f"{amount}р». Другие суммы не называй.")
    else:
        parts.append("ЦЕНА ДЛЯ ЭТОГО ЗАКАЗА. Цену не называй вовсе, только срок.")
    return "\n\n".join(parts)

#: Пока отправленных откликов меньше этого, все заходы идут поровну: на пяти
#: откликах «подвох выигрывает» означает только то, что подвоху повезло.
ANGLE_MIN_SAMPLE = 20

#: Доля выбора, которую заход сохраняет даже при нулевой статистике. Без неё
#: первый же удачный заход вытеснил бы остальные и мерить стало бы нечего.
ANGLE_FLOOR = 0.1


def pick_angle(stats: list = None) -> str:
    """Каким заходом писать следующий отклик.

    Пока данных мало — просто по кругу, случайно и поровну. Когда отправленных
    откликов набирается достаточно, заход с лучшей долей ответов выбирается
    чаще, но остальные не выключаются совсем: иначе статистика по ним
    замёрзнет на том, что было, и проверить её уже не выйдет.
    """
    keys = sorted(ANGLES)
    used = sum(row.get("used", 0) for row in (stats or []))
    if not stats or used < ANGLE_MIN_SAMPLE:
        return random.choice(keys)

    rates = {}
    for key in keys:
        row = next((r for r in stats if r.get("angle") == key), None)
        if not row or not row.get("used"):
            # Заход, которым ещё не писали, должен получить свой шанс — иначе
            # он навсегда останется непроверенным.
            rates[key] = 1.0
            continue
        rates[key] = row.get("answered", 0) / row["used"]

    total = sum(rates.values())
    if total <= 0:
        return random.choice(keys)
    weights = [ANGLE_FLOOR + (1 - ANGLE_FLOOR * len(keys)) * rates[k] / total
               for k in keys]
    return random.choices(keys, weights=weights)[0]

